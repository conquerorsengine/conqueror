    // Lit / Unlit: yerleşik PBR shader'ın köşe aşaması (MultiMesh örnekleme ve köşe rengi dahil)
    static const char* kVertex =
            "#type vertex\n"
            "#version 450 core\n"
            "\n"
            "#include \"Include/FrameData.glsl\"\n"
            "\n"
            "layout(location = 0) in vec3 a_Position;\n"
            "layout(location = 1) in vec3 a_Normal;\n"
            "layout(location = 2) in vec3 a_Tangent;\n"
            "layout(location = 3) in vec2 a_TexCoord;\n"
            "layout(location = 4) in vec2 a_TexCoord2;\n"
            "layout(location = 6) in vec4 a_Color;           // Mesh Paint vertex color\n"
            "uniform int u_UseVertexColor = 0;               // 0: not bound (white; emulated backends default the attribute to black)\n"
            "\n"
            "uniform mat4 u_Transform;\n"
            "uniform mat4 u_NormalMatrix;\n"
            "\n"
            "// MultiMesh (GPU instancing): per-instance local matrix (columns) and color multiplier\n"
            "layout(location = 8) in vec4 a_Instance0;\n"
            "layout(location = 9) in vec4 a_Instance1;\n"
            "layout(location = 10) in vec4 a_Instance2;\n"
            "layout(location = 11) in vec4 a_Instance3;\n"
            "layout(location = 12) in vec4 a_InstanceColor;\n"
            "uniform int u_Instanced = 0;\n"
            "\n"
            "out VS_OUT {\n"
            "    vec3 FragPos;\n"
            "    vec3 Normal;\n"
            "    vec3 Tangent;\n"
            "    vec2 TexCoord;\n"
            "    vec2 TexCoord2;\n"
            "    mat3 TBN;\n"
            "    vec4 Color;\n"
            "} vs_out;\n"
            "\n"
            "void main()\n"
            "{\n"
            "    mat4 model = u_Transform;\n"
            "    mat3 normalMatrix = mat3(u_NormalMatrix);\n"
            "    vec4 tint = vec4(1.0);\n"
            "    if (u_Instanced == 1)\n"
            "    {\n"
            "        model = u_Transform * mat4(a_Instance0, a_Instance1, a_Instance2, a_Instance3);\n"
            "        normalMatrix = transpose(inverse(mat3(model)));\n"
            "        tint = a_InstanceColor;\n"
            "    }\n"
            "    vec4 worldPos = model * vec4(a_Position, 1.0);\n"
            "    vs_out.FragPos = worldPos.xyz;\n"
            "\n"
            "    vec3 N = normalize(normalMatrix * a_Normal);\n"
            "    vec3 T = normalMatrix * a_Tangent;\n"
            "    // Gram-Schmidt; safe fallback for meshes without tangents (zero vector)\n"
            "    T = T - dot(T, N) * N;\n"
            "    if (dot(T, T) < 1e-8)\n"
            "        T = abs(N.y) < 0.999 ? cross(vec3(0.0, 1.0, 0.0), N) : vec3(1.0, 0.0, 0.0);\n"
            "    T = normalize(T);\n"
            "    vec3 B = cross(N, T);\n"
            "\n"
            "    vs_out.Normal = N;\n"
            "    vs_out.Tangent = T;\n"
            "    vs_out.TBN = mat3(T, B, N);\n"
            "    vs_out.TexCoord = a_TexCoord;\n"
            "    vs_out.TexCoord2 = a_TexCoord2;\n"
            "    vs_out.Color = (u_UseVertexColor == 1 ? a_Color : vec4(1.0)) * tint;\n"
            "\n"
            "    gl_Position = CQ_Frame.ViewProjection * worldPos;\n"
            "}\n"
            "\n";

    std::string Lit()
    {
        return std::string("#language GLSL\n// Lit Shader: built-in PBR lighting + your own surface through CQ_UserSurface.\n"
                           "// Assign it to the Shader File slot in the material's Inspector.\n") + kVertex + "\n" +
            "#type fragment\n"
            "#version 450 core\n"
            "\n"
            "// This define adds a surface modification hook to the built-in Lit (PBR) lighting\n"
            "#define CQ_USER_SURFACE\n"
            "#include \"Include/PBRForwardFragment.glsl\"\n"
            "\n"
            "// Modify the surface here (like the surf function of a Unity Surface Shader).\n"
            "// surface: Albedo, Normal, Metallic, Roughness, AO, Emission, Alpha (filled with the material's values)\n"
            "// uv: texture coordinate with tiling / offset applied. CQ_Time() is seconds, CQ_CameraPosition() is the camera.\n"
            "void CQ_UserSurface(inout CQ_Surface surface, vec2 uv)\n"
            "{\n"
            "    // Example: soft rim glow at the edges (Fresnel)\n"
            "    vec3 viewDir = normalize(CQ_CameraPosition() - surface.Position);\n"
            "    float rim = pow(1.0 - max(dot(surface.Normal, viewDir), 0.0), 3.0);\n"
            "    surface.Emission += vec3(0.2, 0.5, 1.0) * rim * 0.5;\n"
            "}\n"
            "\n";
    }

    std::string Unlit()
    {
        return std::string("#language GLSL\n// Unlit Shader: not affected by lights (texture x color + emission). Assign it to the material's Shader File slot.\n") +
               kVertex + "\n" +
            "#type fragment\n"
            "#version 450 core\n"
            "\n"
            "#include \"Include/Common.glsl\"\n"
            "#include \"Include/FrameData.glsl\"\n"
            "#include \"Include/Lighting.glsl\"\n"
            "\n"
            "layout(location = 0) out vec4 FragColor;\n"
            "layout(location = 1) out vec4 CQ_GBufferNormal;\n"
            "layout(location = 2) out vec4 CQ_GBufferAlbedo;\n"
            "\n"
            "in VS_OUT {\n"
            "    vec3 FragPos;\n"
            "    vec3 Normal;\n"
            "    vec3 Tangent;\n"
            "    vec2 TexCoord;\n"
            "    vec2 TexCoord2;\n"
            "    mat3 TBN;\n"
            "    vec4 Color;\n"
            "} fs_in;\n"
            "\n"
            "// Material values (Base Map / Base Color / Emission / Tiling in the Inspector)\n"
            "struct UnlitMaterial {\n"
            "    vec3 Albedo;\n"
            "    vec3 EmissionColor;\n"
            "    float EmissionStrength;\n"
            "    vec2 Tiling;\n"
            "    vec2 Offset;\n"
            "};\n"
            "uniform UnlitMaterial u_Material;\n"
            "uniform sampler2D u_AlbedoMap;\n"
            "uniform bool u_UseAlbedoMap;\n"
            "uniform float u_Opacity = 1.0;\n"
            "uniform int u_RenderMode = 0;\n"
            "uniform float u_AlphaClip = 0.5;\n"
            "\n"
            "void main()\n"
            "{\n"
            "    vec2 uv = fs_in.TexCoord * u_Material.Tiling + u_Material.Offset;\n"
            "    vec4 tex = u_UseAlbedoMap ? texture(u_AlbedoMap, uv) : vec4(1.0);\n"
            "    float alpha = tex.a * u_Opacity;\n"
            "    if (u_RenderMode == 1 && alpha < u_AlphaClip)\n"
            "        discard;\n"
            "    vec3 color = SRGBToLinear(tex.rgb * u_Material.Albedo) + u_Material.EmissionColor * u_Material.EmissionStrength;\n"
            "    FragColor = CQ_FinalizeOutput(vec4(color, u_RenderMode == 2 ? alpha : 1.0));\n"
            "    // Unlit surface: keep screen-space effects away from it\n"
            "    CQ_GBufferNormal = vec4(0.0);\n"
            "    CQ_GBufferAlbedo = vec4(0.0);\n"
            "}\n"
            "\n";
    }

    std::string UI()
    {
        return std::string(
            "#language GLSL\n"
            "// UI Shader: draws an Image or Raw Image with your own fragment code. Put this file in a material's Shader slot\n"
            "// and drop the material on the Image's Material slot. With a Position As UV1 component on the same object,\n"
            "// v_UV1 is each vertex's local position (relative to the pivot, in canvas pixels).\n"
            "#type vertex\n"
            "#version 460 core\n"
            "\n"
            "layout(location = 0) in vec3 a_Position;\n"
            "layout(location = 1) in vec4 a_Color;\n"
            "layout(location = 2) in vec2 a_TexCoord;\n"
            "layout(location = 3) in float a_TexIndex;\n"
            "layout(location = 4) in float a_TilingFactor;\n"
            "layout(location = 5) in vec2 a_UV1;\n"
            "\n"
            "uniform mat4 u_ViewProjection;\n"
            "\n"
            "out vec4 v_Color;\n"
            "out vec2 v_TexCoord;\n"
            "out vec2 v_UV1;\n"
            "out flat int v_TexIndex;\n"
            "\n"
            "void main()\n"
            "{\n"
            "    v_Color = a_Color;\n"
            "    v_TexCoord = a_TexCoord;\n"
            "    v_UV1 = a_UV1;\n"
            "    v_TexIndex = int(a_TexIndex + 0.5);\n"
            "    gl_Position = u_ViewProjection * vec4(a_Position, 1.0);\n"
            "}\n"
            "\n"
            "#type fragment\n"
            "#version 460 core\n"
            "\n"
            "#include \"Include/Common.glsl\"\n"
            "#include \"Include/FrameData.glsl\"\n"
            "\n"
            "layout(location = 0) out vec4 FragColor;\n"
            "\n"
            "in vec4 v_Color;\n"
            "in vec2 v_TexCoord;\n"
            "in vec2 v_UV1;\n"
            "in flat int v_TexIndex;\n"
            "\n"
            "uniform sampler2D u_Textures[31];\n"
            "uniform int u_OutputMode = -1;\n"
            "\n"
            "// Material values (Base Color, Opacity, Tiling and Offset in the material Inspector)\n"
            "struct UIMaterial {\n"
            "    vec3 Albedo;\n"
            "    vec2 Tiling;\n"
            "    vec2 Offset;\n"
            "};\n"
            "uniform UIMaterial u_Material;\n"
            "uniform float u_Opacity = 1.0;\n"
            "\n"
            "// The image's texture is one of the batch slots (a switch keeps every index constant)\n"
            "vec4 SampleTexture(int index, vec2 uv)\n"
            "{\n"
            "    switch (index)\n"
            "    {\n"
            "        case 0: return texture(u_Textures[0], uv);\n"
            "        case 1: return texture(u_Textures[1], uv);\n"
            "        case 2: return texture(u_Textures[2], uv);\n"
            "        case 3: return texture(u_Textures[3], uv);\n"
            "        case 4: return texture(u_Textures[4], uv);\n"
            "        case 5: return texture(u_Textures[5], uv);\n"
            "        case 6: return texture(u_Textures[6], uv);\n"
            "        case 7: return texture(u_Textures[7], uv);\n"
            "        case 8: return texture(u_Textures[8], uv);\n"
            "        case 9: return texture(u_Textures[9], uv);\n"
            "        case 10: return texture(u_Textures[10], uv);\n"
            "        case 11: return texture(u_Textures[11], uv);\n"
            "        case 12: return texture(u_Textures[12], uv);\n"
            "        case 13: return texture(u_Textures[13], uv);\n"
            "        case 14: return texture(u_Textures[14], uv);\n"
            "        case 15: return texture(u_Textures[15], uv);\n"
            "        case 16: return texture(u_Textures[16], uv);\n"
            "        case 17: return texture(u_Textures[17], uv);\n"
            "        case 18: return texture(u_Textures[18], uv);\n"
            "        case 19: return texture(u_Textures[19], uv);\n"
            "        case 20: return texture(u_Textures[20], uv);\n"
            "        case 21: return texture(u_Textures[21], uv);\n"
            "        case 22: return texture(u_Textures[22], uv);\n"
            "        case 23: return texture(u_Textures[23], uv);\n"
            "        case 24: return texture(u_Textures[24], uv);\n"
            "        case 25: return texture(u_Textures[25], uv);\n"
            "        case 26: return texture(u_Textures[26], uv);\n"
            "        case 27: return texture(u_Textures[27], uv);\n"
            "        case 28: return texture(u_Textures[28], uv);\n"
            "        case 29: return texture(u_Textures[29], uv);\n"
            "        case 30: return texture(u_Textures[30], uv);\n"
            "    }\n"
            "    return texture(u_Textures[0], uv);\n"
            "}\n"
            "\n"
            "void main()\n"
            "{\n"
            "    vec4 color = SampleTexture(v_TexIndex, v_TexCoord * u_Material.Tiling + u_Material.Offset) * v_Color;\n"
            "    color *= vec4(u_Material.Albedo, u_Opacity);\n"
            "\n"
            "    // Example (needs Position As UV1): darken from left to right across a 200 pixel wide image\n"
            "    // color.rgb *= mix(1.0, 0.5, clamp(v_UV1.x / 200.0 + 0.5, 0.0, 1.0));\n"
            "    // Time in seconds: CQ_Frame.CameraPosTime.w\n"
            "\n"
            "    if (color.a < 0.01)\n"
            "        discard;\n"
            "    // The HDR pipeline works in linear color: convert like the default UI shader\n"
            "    bool linearOut = u_OutputMode == 1 || (u_OutputMode < 0 && CQ_Frame.FeatureFlags.x == 1);\n"
            "    if (linearOut)\n"
            "        color.rgb = SRGBToLinear(color.rgb);\n"
            "    FragColor = color;\n"
            "}\n");
    }

    std::string ImageEffect()
    {
        return
            "// Image Effect Shader: applied to the camera image with a Full Screen Pass component.\n"
            "// Effect(uv) returns the final color. Available variables:\n"
            "//   u_Source (scene color), u_Depth (depth), u_Time (s), u_Resolution (pixels), u_Intensity (0..1, blend)\n"
            "vec4 Effect(vec2 uv)\n"
            "{\n"
            "    vec4 color = texture(u_Source, uv);\n"
            "    // Example: invert the colors\n"
            "    return vec4(1.0 - color.rgb, color.a);\n"
            "}\n"
            "\n";
    }

    std::string Compute()
    {
        return
            "// Compute Shader: dispatched from a script.\n"
            "//   ComputeSetTexture(\"Assets/<this file>.comp\", \"u_Result\", \"Assets/<render texture>.cqrt\");\n"
            "//   ComputeSetFloat(\"Assets/<this file>.comp\", \"u_Time\", Time());\n"
            "//   ComputeDispatch(\"Assets/<this file>.comp\", width / 8, height / 8, 1);\n"
            "#version 450 core\n"
            "layout(local_size_x = 8, local_size_y = 8, local_size_z = 1) in;\n"
            "\n"
            "layout(rgba8) uniform image2D u_Result;   // output texture (Render Texture)\n"
            "uniform float u_Time;\n"
            "\n"
            "void main()\n"
            "{\n"
            "    ivec2 pixel = ivec2(gl_GlobalInvocationID.xy);\n"
            "    ivec2 size = imageSize(u_Result);\n"
            "    if (pixel.x >= size.x || pixel.y >= size.y)\n"
            "        return;\n"
            "    vec2 uv = vec2(pixel) / vec2(size);\n"
            "    // Example: animated wave pattern\n"
            "    float v = 0.5 + 0.5 * sin(uv.x * 20.0 + u_Time * 3.0) * cos(uv.y * 20.0 - u_Time * 2.0);\n"
            "    imageStore(u_Result, pixel, vec4(v, uv.x, 1.0 - v, 1.0));\n"
            "}\n";
    }

    std::string RayTracing()
    {
        return
            "// Ray Tracing Shader: casts rays against the scene triangles (BVH, GPU compute). From a script:\n"
            "//   RayTracingDispatch(\"Assets/<this file>.cqraytrace\", \"Assets/<render texture>.cqrt\");\n"
            "// Available: CQ_CameraRay(uv, origin, direction), CQ_TraceRay(origin, direction, maxDistance, hit) -> bool,\n"
            "//            hit.Distance / Position / Normal / Albedo, u_SunDirection (direction the light travels), u_SunColor, u_Time\n"
            "vec4 RayGeneration(ivec2 pixel, vec2 uv)\n"
            "{\n"
            "    vec3 origin, direction;\n"
            "    CQ_CameraRay(uv, origin, direction);\n"
            "    CQ_RayHit hit;\n"
            "    if (!CQ_TraceRay(origin, direction, 1000.0, hit))\n"
            "        return vec4(0.45, 0.6, 0.85, 1.0);   // sky\n"
            "    // Ray-traced shadow: a second ray toward the sun\n"
            "    vec3 toSun = -normalize(u_SunDirection);\n"
            "    CQ_RayHit blocker;\n"
            "    bool shadowed = CQ_TraceRay(hit.Position + hit.Normal * 0.01, toSun, 1000.0, blocker);\n"
            "    float light = shadowed ? 0.0 : max(dot(hit.Normal, toSun), 0.0);\n"
            "    vec3 color = hit.Albedo.rgb * (0.2 + 0.8 * light * u_SunColor);\n"
            "    return vec4(color, 1.0);\n"
            "}\n";
    }

    std::string CustomRenderTexture()
    {
        return
            "// Custom Render Texture Shader: assigned to the \"Shader\" slot of a Custom Render Texture asset.\n"
            "// Update(uv) returns the new texture color. Available variables:\n"
            "//   u_SelfTexture (previous frame, when Double Buffered is on), u_InitTexture, u_Time, u_DeltaTime, u_Resolution, u_FrameCount\n"
            "vec4 Update(vec2 uv)\n"
            "{\n"
            "    vec4 previous = texture(u_SelfTexture, uv);\n"
            "    // Example: rings spreading outward while the previous frame slowly fades\n"
            "    float ring = smoothstep(0.02, 0.0, abs(length(uv - 0.5) - fract(u_Time * 0.5) * 0.7));\n"
            "    return max(previous * 0.96, vec4(vec3(ring), 1.0));\n"
            "}\n"
            "\n";
    }
