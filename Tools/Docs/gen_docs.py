#!/usr/bin/env python3
"""Generates the reference pages in Docs/Reference from the engine's live registries.

Usage:
    1. Dump the registries from the editor (automation command):
           docs_dump <dump dir>
       e.g. CQ_AUTOMATION=script.txt ./ConquerorEngine <project>   with script.txt containing "wait 30", "docs_dump /tmp/cqdocs", "quit"
    2. python3 Tools/Docs/gen_docs.py <dump dir> [repo root]

Writes Components.md, ScriptingAPI.md, ConsoleVariables.md and Automation.md. Automation command descriptions come from
the comment / usage string next to each RegisterCommand in the source, so they stay in sync with the code.
"""
import json
import os
import re
import sys
from collections import OrderedDict, defaultdict

HEADER = "<!-- Generated by Tools/Docs/gen_docs.py from the engine's registries. Do not edit by hand. -->\n\n"


def md_escape(text):
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def anchor(text):
    return re.sub(r"[^a-z0-9 -]", "", text.lower()).strip().replace(" ", "-")


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", path)


def components_page(components):
    by_cat = defaultdict(list)
    for c in components:
        by_cat[c["category"] or "Other"].append(c)
    out = [HEADER, "# Components\n\n",
           "Every component that can be added to an entity (Inspector > Add Component, `comp add <Entity> <Component>` in automation, "
           "`AddComponent(\"Name\")` from scripts). Field names are the keys used in scene files and by `GetComponentField` / "
           "`SetComponentField` in scripts; defaults are the values of a freshly added component.\n\n",
           f"{len(components)} components in {len(by_cat)} categories.\n\n## Categories\n\n"]
    for cat in sorted(by_cat):
        names = ", ".join(f"[{c['name']}](#{anchor(c['name'])})" for c in sorted(by_cat[cat], key=lambda c: c["name"]))
        out.append(f"- **{cat}**: {names}\n")
    for cat in sorted(by_cat):
        out.append(f"\n## {cat}\n")
        for c in sorted(by_cat[cat], key=lambda c: c["name"]):
            out.append(f"\n### {c['name']}\n\n")
            if c["description"]:
                out.append(md_escape(c["description"]) + "\n\n")
            meta = [f"Type `{c['type']}`"]
            if c["script"] and c["script"] != c["type"]:
                meta.append(f"script name `{c['script']}`")
            if c["requires"]:
                meta.append("requires " + ", ".join(f"`{r}`" for r in c["requires"]))
            out.append("; ".join(meta) + ".\n\n")
            if not c["fields"]:
                out.append("_No editable fields (edited with its own inspector or from code)._\n")
                continue
            out.append("| Field | Key | Type | Default | Description |\n|---|---|---|---|---|\n")
            for f in c["fields"]:
                desc = md_escape(f["tooltip"])
                if f["options"]:
                    desc = (desc + " " if desc else "") + "Options: " + ", ".join(f["options"]) + "."
                label = md_escape(f["label"])
                if f["header"]:
                    label = f"_{md_escape(f['header'])}_: " + label
                default = md_escape(f["default"])
                if len(default) > 40:
                    default = default[:37] + "..."
                out.append(f"| {label} | `{f['name']}` | {f['kind']} | {('`' + default + '`') if default else ''} | {desc} |\n")
    return "".join(out)


def natives_page(natives):
    by_cat = defaultdict(list)
    for n in natives:
        by_cat[n["category"] or "Other"].append(n)
    out = [HEADER, "# Scripting API\n\n",
           "Native functions available to every scripting language (ConquerorScript, Luau, LuaQ, Python, C#, Java, C++, C, Rust, Zig "
           "and Visual Script nodes). The names are identical in all languages; see [Scripting](../Scripting.md) for how each language "
           "calls them. Functions that act on \"this\" use the entity the script is attached to.\n\n",
           f"{len(natives)} functions in {len(by_cat)} categories.\n\n## Categories\n\n"]
    for cat in sorted(by_cat):
        out.append(f"- [{cat}](#{anchor(cat)}) ({len(by_cat[cat])})\n")
    for cat in sorted(by_cat):
        out.append(f"\n## {cat}\n\n| Function | Description |\n|---|---|\n")
        for n in sorted(by_cat[cat], key=lambda n: n["name"].lower()):
            out.append(f"| `{md_escape(n['signature'])}` | {md_escape(n['description'])} |\n")
    return "".join(out)


def console_page(console):
    variables = sorted(console["variables"], key=lambda v: v["name"].lower())
    groups = OrderedDict()
    for v in variables:
        prefix = v["name"].split(".")[0] if "." in v["name"] else "misc"
        groups.setdefault(prefix, []).append(v)
    titles = {"r": "Rendering", "t": "Time", "au": "Audio", "p": "Physics", "ai": "AI", "input": "Input", "ui": "UI", "net": "Networking"}
    out = [HEADER, "# Console variables and commands\n\n",
           "Open the Console panel and type a name to read it, `name value` to set it, `name default` to restore it. Values set here "
           "override the scene / project settings at runtime. `Config/ConsoleVariables.ini` in the project is applied on load "
           "(one `name value` per line). Scripts use `CVarGet` / `CVarSet` / `ConsoleCommand`.\n\n"]
    for prefix, vs in groups.items():
        out.append(f"## {titles.get(prefix, prefix)} (`{prefix}.*`)\n\n| Variable | Default | Description |\n|---|---|---|\n")
        for v in vs:
            out.append(f"| `{v['name']}` | `{md_escape(v['value'])}` | {md_escape(v['description'])} |\n")
        out.append("\n")
    out.append("## Commands\n\n| Command | Description |\n|---|---|\n")
    for c in sorted(console["commands"], key=lambda c: c["name"].lower()):
        out.append(f"| `{c['name']}` | {md_escape(c['description'])} |\n")
    return "".join(out)


