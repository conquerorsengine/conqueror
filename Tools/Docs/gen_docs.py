def automation_docs(repo):
    """name -> description from the source (comment inside / above the handler, or the usage string)."""
    docs = {}
    reg = re.compile(r'RegisterCommand\("([A-Za-z0-9_]+)"')
    files = []
    for root, _, names in os.walk(os.path.join(repo, "Editor", "src")):
        files += [os.path.join(root, n) for n in names if n.endswith(".cpp")]
    for root, _, names in os.walk(os.path.join(repo, "Engine", "src")):
        files += [os.path.join(root, n) for n in names if n.endswith(".cpp")]
    for path in files:
        try:
            lines = open(path, encoding="utf-8").read().split("\n")
        except (OSError, UnicodeDecodeError):
            continue
        for i, line in enumerate(lines):
            m = reg.search(line)
            if not m or "Automation::" not in line:
                continue
            name = m.group(1)
            comment = []
            j = i + 1
            while j < len(lines) and lines[j].strip().startswith("//"):
                comment.append(lines[j].strip()[2:].strip())
                j += 1
            if not comment:
                k = i - 1
                while k >= 0 and lines[k].strip().startswith("//"):
                    comment.insert(0, lines[k].strip()[2:].strip())
                    k -= 1
            usage = ""
            for k in range(i, min(i + 6, len(lines))):
                u = re.search(r'err = "([^"]+)"', lines[k])
                if u and u.group(1).split(" ")[0] == name:
                    usage = u.group(1)
                    break
            docs[name] = (" ".join(comment), usage)
    # Yerleşik komutlar (Automation.cpp: if (cmd == "x"))
    auto = os.path.join(repo, "Engine", "src", "Core", "Automation", "Automation.cpp")
    if os.path.exists(auto):
        lines = open(auto, encoding="utf-8").read().split("\n")
        for i, line in enumerate(lines):
            for name in re.findall(r'cmd == "([a-z_]+)"', line):
                if name in docs:
                    continue
                comment = []
                k = i - 1
                while k >= 0 and lines[k].strip().startswith("//"):
                    comment.insert(0, lines[k].strip()[2:].strip())
                    k -= 1
                docs[name] = (" ".join(comment), "")
    return docs


def automation_page(names, repo):
    docs = automation_docs(repo)
    all_names = sorted(set(names) | set(docs))
    out = [HEADER, "# Automation commands\n\n",
           "The editor and players can be driven by a text script (one command per line) for automated tests and tooling: set "
           "`CQ_AUTOMATION=<script>` and start the executable. Results are written to `<script>.result.txt`; every command logs OK or "
           "FAIL. See [Testing](../Testing.md) for the workflow. `wait <frames>`, `screenshot <png>` and `quit` are always available; "
           "the rest are registered by the editor / runtime.\n\n",
           "Descriptions are taken from the comments next to each command in the source (Turkish comments are kept as written).\n\n",
           "| Command | Description |\n|---|---|\n"]
    for n in all_names:
        comment, usage = docs.get(n, ("", ""))
        desc = md_escape(comment) or BUILTIN_AUTOMATION.get(n, "")
        if usage and usage not in desc:
            desc = (desc + " " if desc else "") + f"Usage: `{md_escape(usage)}`"
        out.append(f"| `{n}` | {desc} |\n")
    return "".join(out)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    dump = sys.argv[1]
    repo = sys.argv[2] if len(sys.argv) > 2 else os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    out_dir = os.path.join(repo, "Docs", "Reference")
    load = lambda n: json.load(open(os.path.join(dump, n), encoding="utf-8"))
    write(os.path.join(out_dir, "Components.md"), components_page(load("components.json")))
    write(os.path.join(out_dir, "ScriptingAPI.md"), natives_page(load("natives.json")))
    write(os.path.join(out_dir, "ConsoleVariables.md"), console_page(load("console.json")))
    write(os.path.join(out_dir, "Automation.md"), automation_page(load("automation.json"), repo))
    return 0


if __name__ == "__main__":
    sys.exit(main())
