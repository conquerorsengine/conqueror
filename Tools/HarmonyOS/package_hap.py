#!/usr/bin/env python3
"""Conqueror Engine -> HarmonyOS HAP projesi (HarmonyOS 5+ PC "2in1" ve tablet).

OpenHarmony NDK ile derlenen editörü (libConquerorEditor.so) ya da oyuncuyu (libconqueror.so) Tools/HarmonyOS/template
şablonundan bir DevEco / hvigor projesine koyar: .so dosyaları entry/libs/<abi>/, motor kaynakları (editör) ya da derlenmiş oyun
klasörü (oyuncu) entry/src/main/resources/rawfile/ altına (cq_files.txt listesiyle; uygulama ilk açılışta filesDir'e çıkarır).

  # editör (arm64-v8a ve x86_64 derleme klasörleri)
  python3 Tools/HarmonyOS/package_hap.py --out build/hap-editor --build-dir build/ohos-arm64 --build-dir build/ohos-x86_64
  # oyuncu: editörde Build ile üretilen oyun klasörü
  python3 Tools/HarmonyOS/package_hap.py --out build/hap-game --player Builds/MyGame --build-dir build/ohos-arm64
  # isteğe bağlı: HAP'i hvigor ile derle (DevEco Studio ya da HarmonyOS komut satırı araçları; hvigorw PATH'te)
  python3 Tools/HarmonyOS/package_hap.py ... --assemble

Derleme (OpenHarmony native SDK, ör. 6.0 Release):
  cmake -S . -B build/ohos-arm64 -G Ninja -DCMAKE_BUILD_TYPE=Release \\
        -DCMAKE_TOOLCHAIN_FILE=<sdk>/native/build/cmake/ohos.toolchain.cmake -DOHOS_ARCH=arm64-v8a -DOHOS_STL=c++_static
  cmake --build build/ohos-arm64 --target ConquerorEngine conqueror

HAP'in kurulabilmesi için imza gerekir (DevEco Studio > Project Structure > Signing Configs; HarmonyOS cihazlarda AppGallery
Connect hata ayıklama sertifikası). İmzasız HAP yalnız paket yapısının denetimi içindir.
"""

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ENGINE_ROOT = Path(__file__).resolve().parents[2]
TEMPLATE = Path(__file__).resolve().parent / "template"
MARKER = ".cq_hap_project"
ABIS = ("arm64-v8a", "x86_64", "armeabi-v7a")
TEXT_SUFFIXES = {".json5", ".json", ".ets", ".ts"}
# Libc++ paylaşımlı derlemede (OHOS_STL=c++_shared) .so'nun yanına konur
LIBCXX_TRIPLES = {"arm64-v8a": "aarch64-linux-ohos", "x86_64": "x86_64-linux-ohos", "armeabi-v7a": "arm-linux-ohos"}


def log(msg):
    print(f"[package_hap] {msg}", flush=True)


def fail(msg):
    print(f"[package_hap] ERROR: {msg}", file=sys.stderr, flush=True)
    sys.exit(1)


def engine_version():
    text = (ENGINE_ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
    m = re.search(r"project\(ConquerorEngine VERSION ([0-9.]+)", text)
    return m.group(1) if m else "1.0.0"


def version_code(version):
    # 0.571.3 -> 571003 (HarmonyOS versionCode: artan tam sayı)
    parts = [int(p) for p in version.split(".")[:3]] + [0, 0, 0]
    return parts[0] * 100000000 + parts[1] * 1000 + parts[2]


def prepare_output(out):
    if out.exists():
        if not (out / MARKER).is_file() and any(out.iterdir()):
            fail(f"{out} exists and is not a previous HAP project from this script (no {MARKER}); choose an empty folder")
        # Önceki çıktının yalnız üretilen kısımları yenilenir (hvigor önbelleği / imza ayarları kalır)
        for generated in (out / "entry" / "libs", out / "entry" / "src" / "main" / "resources" / "rawfile"):
            if generated.is_dir():
                shutil.rmtree(generated)
    out.mkdir(parents=True, exist_ok=True)


def copy_template(out, values, openharmony):
    for src in TEMPLATE.rglob("*"):
        rel = src.relative_to(TEMPLATE)
        dst = out / rel
        if src.is_dir():
            dst.mkdir(parents=True, exist_ok=True)
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        if src.suffix in TEXT_SUFFIXES:
            text = src.read_text(encoding="utf-8")
            for key, value in values.items():
                text = text.replace(f"@{key}@", value)
            if openharmony and rel.as_posix() == "build-profile.json5":
                # OpenHarmony SDK ile derleme (DevEco olmadan, hvigor + OpenHarmony public SDK): sürümler API numarası
                text = text.replace('"compatibleSdkVersion": "5.0.0(12)",\n        "runtimeOS": "HarmonyOS",',
                                    '"compileSdkVersion": 20,\n        "compatibleSdkVersion": 12,\n        "runtimeOS": "OpenHarmony",')
            dst.write_text(text, encoding="utf-8")
        else:
            shutil.copy2(src, dst)
    (out / MARKER).write_text("generated by Tools/HarmonyOS/package_hap.py\n", encoding="utf-8")


def copy_icons(out):
    icon = ENGINE_ROOT / "Resources" / "Logo" / "AppIcon" / "conqueror_256.png"
    if not icon.is_file():
        fail(f"app icon not found: {icon}")
    for dst in (out / "AppScope" / "resources" / "base" / "media" / "app_icon.png",
                out / "entry" / "src" / "main" / "resources" / "base" / "media" / "icon.png"):
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(icon, dst)


def find_sdk_native(explicit):
    for candidate in (explicit, os.environ.get("OHOS_SDK_NATIVE"), os.environ.get("OHOS_NDK_HOME")):
        if candidate and (Path(candidate) / "llvm").is_dir():
            return Path(candidate)
        if candidate and (Path(candidate) / "native" / "llvm").is_dir():
            return Path(candidate) / "native"
    return None


def copy_libraries(out, build_dirs, library, sdk_native):
    found = []
    for build_dir in build_dirs:
        for abi in ABIS:
            lib = build_dir / "lib" / abi / f"lib{library}.so"
            if not lib.is_file():
                continue
            dst_dir = out / "entry" / "libs" / abi
            dst_dir.mkdir(parents=True, exist_ok=True)
            shutil.copy2(lib, dst_dir / lib.name)
            found.append(abi)
            log(f"{abi}: {lib} ({lib.stat().st_size // (1024 * 1024)} MB)")
            # c++_shared ile derlendiyse libc++_shared.so da gerekir (NEEDED kaydı .dynstr'de)
            if b"libc++_shared.so" in lib.read_bytes():
                if not sdk_native:
                    fail(f"{lib.name} needs libc++_shared.so: pass --sdk <OpenHarmony SDK native folder> or build with -DOHOS_STL=c++_static")
                libcxx = sdk_native / "llvm" / "lib" / LIBCXX_TRIPLES[abi] / "libc++_shared.so"
                if not libcxx.is_file():
                    fail(f"libc++_shared.so not found: {libcxx}")
                shutil.copy2(libcxx, dst_dir / libcxx.name)
    if not found:
        fail(f"lib{library}.so not found under <build-dir>/lib/<abi>/ (build the {'ConquerorEngine' if library == 'ConquerorEditor' else 'conqueror'} target first)")
    return found


def content_files(player):
    """(kaynak, rawfile içindeki göreli yol) çiftleri."""
    pairs = []

    def add_tree(root, prefix):
        for path in sorted(root.rglob("*")):
            if not path.is_file():
                continue
            rel = path.relative_to(root)
            if any(part.startswith(".") for part in rel.parts) or path.name == "cq_files.txt":
                continue
            pairs.append((path, (Path(prefix) / rel).as_posix() if prefix else rel.as_posix()))

    if player:
        if not any(player.glob("*.cqproj")):
            fail(f"{player} is not a built game folder (no .cqproj)")
        add_tree(player, "")
    else:
        # Editörün masaüstündeki çıktı düzeni (Main/CMakeLists.txt SyncResources): Resources/, Engine/src/Shaders, giriş eşlemesi
        add_tree(ENGINE_ROOT / "Resources", "Resources")
        add_tree(ENGINE_ROOT / "Engine" / "src" / "Shaders", "Engine/src/Shaders")
        default_input = ENGINE_ROOT / "Engine" / "src" / "Core" / "Input" / "default.cqinput"
        pairs.append((default_input, "Engine/src/Core/Input/default.cqinput"))
    return pairs


def copy_content(out, pairs):
    rawfile = out / "entry" / "src" / "main" / "resources" / "rawfile"
    rawfile.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha256()
    total = 0
    for src, rel in pairs:
        dst = rawfile / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        st = src.stat()
        digest.update(f"{rel}\0{st.st_size}\0{int(st.st_mtime)}\n".encode("utf-8"))
        total += st.st_size
    # İlk satır içerik sürümü: değişmediyse uygulama yeniden çıkarmaz (OHOSModule.cpp ExtractRawFiles)
    manifest = [digest.hexdigest()[:16]] + [rel for _, rel in pairs]
    (rawfile / "cq_files.txt").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    log(f"rawfile: {len(pairs)} files, {total // (1024 * 1024)} MB")


def assemble(out):
    hvigorw = shutil.which("hvigorw")
    if not hvigorw:
        fail("hvigorw not found in PATH (install DevEco Studio or the HarmonyOS command line tools, or open the project in DevEco Studio)")
    cmd = [hvigorw, "assembleHap", "--mode", "module", "-p", "product=default", "-p", "buildMode=release", "--no-daemon"]
    log("$ " + " ".join(cmd))
    r = subprocess.run(cmd, cwd=out)
    if r.returncode != 0:
        fail(f"hvigor failed ({r.returncode})")
    haps = sorted((out / "entry" / "build").rglob("*.hap"))
    for hap in haps:
        log(f"HAP: {hap}")


def main():
    ap = argparse.ArgumentParser(description="Package the Conqueror Engine editor or a built game as a HarmonyOS HAP project")
    ap.add_argument("--out", required=True, type=Path, help="output project folder (empty or a previous output)")
    ap.add_argument("--build-dir", action="append", type=Path, default=[], help="OHOS CMake build folder (repeat per architecture)")
    ap.add_argument("--player", type=Path, help="built game folder: package the player (libconqueror.so) instead of the editor")
    ap.add_argument("--bundle-name", help="bundle name (default com.conqueror.editor / com.conqueror.<game>)")
    ap.add_argument("--label", help="app name shown by the system")
    ap.add_argument("--vendor", default="Conqueror Engine")
    ap.add_argument("--version", help="version name (default: engine version)")
    ap.add_argument("--sdk", help="OpenHarmony SDK native folder (only needed for c++_shared builds)")
    ap.add_argument("--openharmony", action="store_true", help="write an OpenHarmony (not HarmonyOS) product: build with hvigor + the OpenHarmony SDK")
    ap.add_argument("--assemble", action="store_true", help="run 'hvigorw assembleHap' in the output folder")
    args = ap.parse_args()

    if not args.build_dir:
        args.build_dir = [ENGINE_ROOT / "build" / "ohos-arm64"]
    player = args.player.resolve() if args.player else None
    if player and not player.is_dir():
        fail(f"game folder not found: {player}")
    library = "conqueror" if player else "ConquerorEditor"
    version = args.version or engine_version()
    game = re.sub(r"[^a-z0-9]", "", player.name.lower()) if player else ""
    values = {
        "CQ_LIBRARY": library,
        "CQ_BUNDLE_NAME": args.bundle_name or (f"com.conqueror.{game or 'game'}" if player else "com.conqueror.editor"),
        "CQ_APP_LABEL": args.label or (player.name if player else "Conqueror Engine"),
        "CQ_VENDOR": args.vendor,
        "CQ_VERSION_NAME": version,
        "CQ_VERSION_CODE": str(version_code(version)),
    }

    out = args.out.resolve()
    prepare_output(out)
    copy_template(out, values, args.openharmony)
    copy_icons(out)
    abis = copy_libraries(out, [b.resolve() for b in args.build_dir], library, find_sdk_native(args.sdk))
    copy_content(out, content_files(player))
    log(f"{'player' if player else 'editor'} project ready: {out} ({', '.join(abis)}; bundle {values['CQ_BUNDLE_NAME']})")
    if args.assemble:
        assemble(out)
    else:
        log("Build the HAP with DevEco Studio (open the folder) or: hvigorw assembleHap --mode module -p product=default --no-daemon")


if __name__ == "__main__":
    main()
